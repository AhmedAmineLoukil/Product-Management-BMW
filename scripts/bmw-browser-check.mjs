import {chromium,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const results=[];
const pass=(name)=>{results.push(name);console.log('PASS',name);};
const nav=async(name)=>{await page.locator('.sidebar nav').getByRole('button',{name,exact:name!=='Review Queue'}).click();await expect(page.locator('h1')).toHaveText(name);};
try{
 await page.goto('http://127.0.0.1:5173/#data-sources',{waitUntil:'domcontentloaded'});
 await expect(page.getByRole('heading',{name:'BMW data library'})).toBeVisible();
 await page.getByLabel('BMW library vehicle').selectOption('F70');
 await page.getByLabel('BMW library market').selectOption('EU');
 await expect(page.getByText('1,433').first()).toBeVisible();
 await page.getByRole('button',{name:'Load this vehicle + market'}).click();
 await expect(page.locator('.context-switcher')).toContainText('BMW 1 Series F70');
 await expect(page.locator('.context-switcher')).toContainText('Europe');
 await expect(page.locator('.source-card')).toContainText(['Customer verbatims']);
 await expect(page.locator('.source-card').first()).toContainText('1433 records');
 pass('F70/Europe source import with original country labels retained');
 await page.reload({waitUntil:'domcontentloaded'});
 await expect(page.locator('.source-card').first()).toContainText('1433 records');
 pass('Large supplied data survives reload in browser database');
 await page.locator('.source-card').first().getByRole('button',{name:'Preview records'}).click();
 await expect(page.getByRole('dialog')).toContainText('1433 records');
 await page.getByRole('dialog').getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('button',{name:'Run demo analysis'}).click();
 await expect(page.getByText('Analysis complete. Results and source links are recorded in the audit trail.')).toBeVisible();
 await nav('Review Queue');
 await expect(page.locator('.review-card').first()).toBeVisible();
 pass('Full feedback set produces reviewable proposals with source links');
 await nav('Data Sources');
 await page.getByLabel('BMW library vehicle').selectOption('G68');
 await page.getByLabel('BMW library market').selectOption('CN');
 await expect(page.getByText('No customer verbatims were supplied')).toBeVisible();
 await page.getByRole('button',{name:'Load this vehicle + market'}).click();
 await expect(page.locator('.context-switcher')).toContainText('BMW 5 Series G68');
 await expect(page.locator('.context-switcher')).toContainText('China');
 await expect(page.locator('.source-card')).toHaveCount(2);
 await expect(page.locator('.source-card').first()).toContainText('Customer study');
 await expect(page.locator('.source-card').nth(1)).toContainText('Sales volumes');
 await expect(page.getByRole('button',{name:'Run demo analysis'})).toBeDisabled();
 pass('G68/China stays separate and does not invent customer feedback');
 await page.getByLabel('BMW library vehicle').selectOption('F70');
 await page.getByLabel('BMW library market').selectOption('EU');
 await page.getByRole('button',{name:'Load this vehicle + market'}).click();
 await expect(page.locator('.context-switcher')).toContainText('Europe');
 await expect(page.locator('.source-card').filter({hasText:'Equipment list'})).toBeVisible();
 pass('F70/Europe includes the German catalog and country-level feedback with distinct provenance');
 await page.getByLabel('BMW library vehicle').selectOption('G70');
 await page.getByLabel('BMW library market').selectOption('US');
 await page.getByRole('button',{name:'Load this vehicle + market'}).click();
 await expect(page.locator('.context-switcher')).toContainText('United States');
 await expect(page.locator('.source-card').filter({hasText:'Customer study'})).toContainText('824 records');
 await expect(page.getByRole('button',{name:'Run demo analysis'})).toBeDisabled();
 pass('G70/US retains US study measures without inventing feedback');
 await page.setViewportSize({width:390,height:844});
 await expect.poll(async()=>page.locator('.sidebar').evaluate(element=>Math.round(element.getBoundingClientRect().right))).toBeLessThanOrEqual(0);
 await expect(page.getByRole('heading',{name:'BMW data library'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await mkdir('artifacts',{recursive:true});
 await page.screenshot({path:'artifacts/bmw-library-mobile.png',fullPage:true});
 pass('BMW library fits mobile viewport');
 expect(errors).toEqual([]);
 console.log(`${results.length} BMW browser scenarios passed.`);
}catch(error){console.error(error);await mkdir('artifacts',{recursive:true});await page.screenshot({path:'artifacts/bmw-library-failure.png',fullPage:true});process.exitCode=1;}finally{await browser.close();}
